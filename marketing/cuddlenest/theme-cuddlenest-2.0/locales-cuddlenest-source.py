import json, re, sys
base = sys.argv[1]
out = sys.argv[2]
assert set(EN) == set(FR)
for sec in EN:
    assert set(EN[sec]) == set(FR[sec]), (sec, set(EN[sec]) ^ set(FR[sec]))
for fname, data in (("en.default.json", EN), ("fr.json", FR)):
    raw = open(f"{base}/locales/{fname}").read()
    m = re.match(r"\s*(/\*.*?\*/)\s*", raw, flags=re.S)
    header = m.group(1) + "\n" if m else ""
    body = raw[m.end():] if m else raw
    j = json.loads(body)
    j["cuddlenest"] = data
    open(f"{out}/locales/{fname}", "w").write(header + json.dumps(j, indent=2, ensure_ascii=False) + "\n")
    print(fname, "ok")
